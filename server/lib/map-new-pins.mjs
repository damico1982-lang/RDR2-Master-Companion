function fish(id, title, region, gameX, gameY, county, lure, directions) {
  return {
    id,
    category: "Fish",
    mode: "story",
    title,
    region,
    gameX,
    gameY,
    county,
    obtain: "Wild",
    chapter: region.includes("Epilogue") || directions.startsWith("Epilogue") ? "Epilogue" : "After A Fisher of Fish begins",
    directions: `${directions} Lure: ${lure}. Start A Fisher of Fish with Jeremy Gill, buy the special lures in Lagras, and mail the fish from a post office.`,
    note: "Legendary fish. Pelt-style quality does not apply. Do not let it fall off the horse before you mail it."
  };
}

function weapon(id, title, region, gameX, gameY, county, directions, note) {
  return {
    id,
    category: "Weapons",
    mode: "story",
    title,
    region,
    gameX,
    gameY,
    county,
    obtain: "Unique weapon",
    directions,
    note
  };
}

function shop(id, title, region, gameX, gameY, county, directions) {
  return {
    id,
    category: "Ammo",
    mode: "either",
    title,
    region,
    gameX,
    gameY,
    county,
    shop: true,
    obtain: "Shop",
    directions,
    note: "Shop. Marked as a store, not a one-time crate. Stock depends on chapter and on what the catalog has unlocked."
  };
}

function horse(pin) {
  return {
    category: "Horses",
    mode: "story",
    ...pin
  };
}
